#' @export
ccir_stan_models_binomial_temperature_logistic <- function() {
  
  bino = '
  
  data {
    int<lower=1> n;                   // sample size
    vector<lower=0,upper=1>[n] p;     // observed proportion
    vector<lower=0,upper=1>[n] Cuml;  // cumulative landings
    int N[n];                         // total number observed
    int E[n];                         // number exploitable/legal
    real Temp[n];                     // temperature
    
    // Prior means and standard deviations
    real Ap;
    real Bp;
    real App;
    real Bpp;
    real Dp;
    real Dpp;
  }

  parameters {
    real A;                           // intercept
    real B;                           // cumulative landings coefficient
    real D;                           // temperature coefficient
  }

  transformed parameters {
    vector[n] pp;
    
    for (i in 1:n) {
      // Logistic formulation:
      // logit(pp) = A + B*Cuml + D*Temp
      pp[i] = inv_logit(A + B * Cuml[i] + D * Temp[i]);
    }
  }

  model {
    // Priors
    A ~ normal(Ap, App);
    B ~ normal(Bp, Bpp);
    D ~ normal(Dp, Dpp);

    // Binomial likelihood
    E ~ binomial(N, pp);
  }

  generated quantities {
    vector[n] phat;
    vector[n] ERp;
    
    for (i in 1:n) {
      phat[i] = pp[i];
      
      // Exploitation rate relative to the first observation,
      // calculated from the odds of exploitable lobster.
      ERp[i] = 1 -
        (phat[i] / (1 - phat[i])) /
        (phat[1] / (1 - phat[1]));
    }
  }
  
  '
  
  return(bino)
}


#' @export
ccir_stan_run_binomial_temperature_logistic <- function(
    dat,
    inits = c(A0 = 0.5, B0 = 0.5, D = 0.1),
    save = TRUE,
    season = NULL,
    test = NA
) {
  
  # ------------------------------------------------------------
  # Define prior means using the existing CCIR initialization
  # procedure.
  #
  # These are prior means, NOT Stan starting values.
  # ------------------------------------------------------------
  
  ins <- ccir_inits(
    dat,
    A0 = inits[1],
    B0 = inits[2]
  )
  
  dat$Ap <- as.numeric(ins[1])
  dat$Bp <- as.numeric(ins[2])
  
  # Prior standard deviations
  dat$App <- 5
  dat$Bpp <- 5
  
  # Temperature prior
  dat$Dp <- as.numeric(inits[3])
  dat$Dpp <- 0.4
  
  # Retained for compatibility with the existing data structure
  dat$phip <- 0
  dat$phipp <- 100
  
  
  # ------------------------------------------------------------
  # Model
  # ------------------------------------------------------------
  
  ccir_stan <- ccir_stan_models_binomial_temperature_logistic()
  
  
  # ------------------------------------------------------------
  # Parameters to monitor
  # ------------------------------------------------------------
  
  pars.to.monitor <- c(
    "A",
    "B",
    "D",
    "pp",
    "phat",
    "ERp"
  )
  
  
  # ------------------------------------------------------------
  # Run Stan
  # ------------------------------------------------------------
  
  fit <- stan(
    model_code = ccir_stan,
    model_name = "bino_logistic",
    fit = test,
    data = dat,
    iter = 3500,
    warmup = 1000,
    thin = 10,
    cores = 4,
    verbose = FALSE
  )
  
  
  # ------------------------------------------------------------
  # Output directory
  # ------------------------------------------------------------
  
  fdir <- file.path(
    project.datadirectory("bio.lobster"),
    "outputs",
    "ccir"
  )
  
  if (!dir.exists(fdir)) {
    dir.create(
      fdir,
      recursive = TRUE,
      showWarnings = FALSE
    )
  }
  
  
  # ------------------------------------------------------------
  # Construct output filename
  #
  # "Logistic" is explicitly included so that this cannot
  # overwrite the original CCIR output.
  # ------------------------------------------------------------
  
  ti <- 1
  
  if (!is.null(season)) {
    ti <- season
  }
  
  fname <- paste(
    "LFA",
    dat$LFA,
    "Year",
    dat$Yr,
    ti,
    "Grid",
    paste(min(dat$Grid), max(dat$Grid), sep = "-"),
    "Season",
    paste(min(dat$Seas), max(dat$Seas), sep = "-"),
    "Sex",
    dat$Sex,
    dat$method,
    "Logistic",
    sep = "."
  )
  
  
  # ------------------------------------------------------------
  # Output object
  # ------------------------------------------------------------
  
  out <- list(
    fit = fit,
    dat = dat,
    file = fname,
    test = test
  )
  
  
  # ------------------------------------------------------------
  # Save
  # ------------------------------------------------------------
  
  if (save) {
    save(
      out,
      file = file.path(
        fdir,
        paste(fname, "rdata", sep = ".")
      )
    )
  }
  
  
  return(out)
}

  