# ------------------------------------------------------------
# Function to calculate WAIC from a saved Stan fit
# ------------------------------------------------------------

get_waic <- function(f) {
  
  load(f)
  
  # Extract posterior draws of phat
  phat_draws <- rstan::extract(
    out$fit,
    pars = "phat"
  )$phat
  
  # Calculate pointwise log-likelihood
  log_lik <- sapply(
    1:nrow(phat_draws),
    function(i) {
      dbinom(
        out$dat$E,
        size = out$dat$N,
        prob = phat_draws[i, ],
        log = TRUE
      )
    }
  )
  
  # lppd
  lppd <- sum(
    log(
      apply(log_lik, 2, function(x) {
        mean(exp(x))
      })
    )
  )
  
  # Effective number of parameters
  p_waic <- sum(
    apply(log_lik, 2, var)
  )
  
  # WAIC
  waic <- -2 * (lppd - p_waic)
  
  # Return results
  data.frame(
    file = basename(f),
    WAIC = waic,
    p_WAIC = p_waic,
    lppd = lppd
  )
}


