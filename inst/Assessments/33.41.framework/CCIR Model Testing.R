# ============================================================
# CALCULATE WAIC FROM SAVED CCIR STAN FITS
#
# Purpose:
#   Calculate WAIC from previously saved BINOMIAL and
#   BINOMIAL + TEMPERATURE Stan fits.
#
# Important:
#   This script does NOT rerun the Stan models.
#   It reconstructs the pointwise binomial log-likelihood
#   from the posterior draws of phat and the observed E and N.
#
# Model likelihood:
#   E[i] ~ Binomial(N[i], phat[i])
#
# where:
#   E    = observed number of successful/reference lobsters
#   N    = total number of lobsters/traps
#   phat = posterior predicted probability
# ============================================================


# ------------------------------------------------------------
# 1. Directories
# ------------------------------------------------------------

# These objects should already point to the directories
# containing the saved model fits.

# Example:
#
# binomial_fit_dir <- file.path(
#     ccir.model.testing,
#     "summary/binomial/fits"
# )
#
# binomial_temp_fit_dir <- file.path(
#     ccir.model.testing,
#     "summary/binomial.temp/lfa33/fits"
# )


# ------------------------------------------------------------
# 2. Function to calculate WAIC
# ------------------------------------------------------------

get_waic <- function(fit_file) {
  
  # Load saved fit
  load(fit_file)
  
  # ----------------------------------------------------------
  # Extract posterior draws of phat
  # ----------------------------------------------------------
  
  phat_draws <- rstan::extract(
    out$fit,
    pars = "phat"
  )$phat
  
  # Ensure a simple matrix
  # Rows = posterior draws
  # Columns = observations
  phat_draws <- as.matrix(phat_draws)
  
  
  # ----------------------------------------------------------
  # Observed data
  # ----------------------------------------------------------
  
  E <- out$dat$E
  N <- out$dat$N
  
  
  # ----------------------------------------------------------
  # Pointwise log-likelihood
  #
  # Each posterior draw gets a likelihood for each
  # observation.
  #
  # Result:
  #   rows    = posterior draws
  #   columns = observations
  # ----------------------------------------------------------
  
  log_lik <- t(sapply(
    1:nrow(phat_draws),
    function(i) {
      
      dbinom(
        E,
        size = N,
        prob = phat_draws[i, ],
        log = TRUE
      )
      
    }
  ))
  
  
  # ----------------------------------------------------------
  # Log pointwise predictive density (lppd)
  # ----------------------------------------------------------
  
  lppd <- sum(
    log(
      apply(
        log_lik,
        2,
        function(x) {
          mean(exp(x))
        }
      )
    )
  )
  
  
  # ----------------------------------------------------------
  # Effective number of parameters
  # ----------------------------------------------------------
  
  p_waic <- sum(
    apply(
      log_lik,
      2,
      var
    )
  )
  
  
  # ----------------------------------------------------------
  # WAIC
  # ----------------------------------------------------------
  
  waic <- -2 * (lppd - p_waic)
  
  
  # ----------------------------------------------------------
  # Return results
  # ----------------------------------------------------------
  
  data.frame(
    file = basename(fit_file),
    WAIC = waic,
    p_WAIC = p_waic,
    lppd = lppd
  )
}


